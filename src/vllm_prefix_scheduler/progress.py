"""Evidence-based project progress contracts, independent of the GPU runtime."""

from collections import Counter
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import unquote, urlparse

STATES = {"planned", "ready", "active", "blocked", "done"}
LABELS = {
    "planned": "待开始",
    "ready": "可开始",
    "active": "进行中",
    "blocked": "有阻塞",
    "done": "已验收",
    "partial": "部分验收",
}


def validate_progress(data: dict, root: Path | None = None) -> dict:
    """Require evidence for completion and satisfied dependencies for active work."""
    if data.get("schema_version") != 1:
        raise ValueError("Unsupported project status schema")
    milestones = {item["id"]: item for item in data["milestones"]}
    tasks = {item["id"]: item for item in data["tasks"]}
    if len(milestones) != len(data["milestones"]) or len(tasks) != len(data["tasks"]):
        raise ValueError("Milestone and task IDs must be unique")
    all_done = bool(tasks) and all(task["status"] == "done" for task in tasks.values())
    if all_done:
        if data["focus_task"] is not None:
            raise ValueError("A fully accepted project has no pending focus task")
    else:
        if data["focus_task"] not in tasks:
            raise ValueError("The focus task must exist")
        if tasks[data["focus_task"]]["status"] not in {"ready", "active", "blocked"}:
            raise ValueError("Focus must be an actionable or explicitly blocked task")
    for task in tasks.values():
        if task["milestone"] not in milestones or task["status"] not in STATES:
            raise ValueError(f"Invalid task milestone/status: {task['id']}")
        if not task["acceptance"]:
            raise ValueError(f"Missing acceptance criteria: {task['id']}")
        if any(item not in tasks for item in task["depends_on"]):
            raise ValueError(f"Unknown dependency: {task['id']}")
        if task["status"] in {"done", "ready", "active"} and any(
            tasks[dependency]["status"] != "done" for dependency in task["depends_on"]
        ):
            raise ValueError(f"Unsatisfied dependency: {task['id']}")
        if task["status"] == "done" and not task["evidence"]:
            raise ValueError(f"Completion requires evidence: {task['id']}")
        for evidence in task["evidence"]:
            if not evidence.get("label") or urlparse(evidence.get("url", "")).scheme != "https":
                raise ValueError(f"Evidence requires a labelled HTTPS source: {task['id']}")
        if task["status"] == "blocked" and not task.get("blocker"):
            raise ValueError(f"A blocked task requires a concrete blocker: {task['id']}")

    visiting, visited = set(), set()

    def visit(task_id):
        if task_id in visiting:
            raise ValueError("Task dependencies contain a cycle")
        if task_id in visited:
            return
        visiting.add(task_id)
        for dependency in tasks[task_id]["depends_on"]:
            visit(dependency)
        visiting.remove(task_id)
        visited.add(task_id)

    for task_id in tasks:
        visit(task_id)
    if root is not None:
        repository_path = urlparse(data["project"]["repository"]).path.rstrip("/")
        for task in tasks.values():
            for evidence in task["evidence"]:
                parsed = urlparse(evidence["url"])
                prefix = repository_path + "/blob/main/"
                if parsed.netloc == "github.com" and parsed.path.startswith(prefix):
                    relative = unquote(parsed.path[len(prefix) :])
                    destination = (root / relative).resolve()
                    if not destination.is_relative_to(root.resolve()) or not destination.is_file():
                        raise ValueError(f"Missing repository evidence: {relative}")
    return dict(Counter(task["status"] for task in tasks.values()))


def milestone_status(data: dict, milestone_id: str) -> str:
    tasks = [task for task in data["tasks"] if task["milestone"] == milestone_id]
    states = {task["status"] for task in tasks}
    if states == {"done"}:
        return "done"
    for state in ("blocked", "active"):
        if state in states:
            return state
    if "done" in states:
        return "partial"
    if "ready" in states:
        return "ready"
    return "planned"


def recent_events(data: dict) -> list:
    def timestamp(event):
        value = datetime.fromisoformat(event["date"].replace("Z", "+00:00"))
        return value.replace(tzinfo=UTC) if value.tzinfo is None else value

    return sorted(data["events"], key=timestamp, reverse=True)


def render_state(data: dict) -> str:
    tasks = {task["id"]: task for task in data["tasks"]}
    focus = tasks.get(data["focus_task"])
    counts = validate_progress(data)
    lines = [
        "<!-- Generated by scripts/build_progress.py from progress/project-status.json. -->",
        "# 当前状态与下一步",
        "",
        f"更新：{data['updated_at']}，{data['project']['timezone']}。",
        "",
        data["project"]["description"],
        "",
        "## 协调入口",
        "",
        f"{data['coordination']['role']}。{data['coordination']['cadence']}。",
        "",
        "唯一进度源：[project-status.json](../progress/project-status.json)。"
        "[交互看板](../progress/index.html)和本页由同一份数据生成；"
        "日常更新步骤见[协调约定](coordination.md)。",
        "",
        f"已验收任务 {counts.get('done', 0)} / {len(tasks)}。"
        "这是验收任务计数，不代表工时或项目完成百分比。",
        "",
        "## 里程碑",
        "",
        "| 阶段 | 状态 | 已验收任务 | 目标 |",
        "|---|---|---|---|",
    ]
    for milestone in data["milestones"]:
        phase_tasks = [task for task in tasks.values() if task["milestone"] == milestone["id"]]
        done = sum(task["status"] == "done" for task in phase_tasks)
        status = LABELS[milestone_status(data, milestone["id"])]
        lines.append(
            f"| {milestone['id']} {milestone['title']} | {status} | "
            f"{done}/{len(phase_tasks)} | {milestone['goal']} |"
        )
    if focus is None:
        lines += [
            "",
            "## 项目验收状态",
            "",
            "**所有已定义验收任务均已完成。** 可按阶段回看证据与交付物。",
        ]
    else:
        lines += [
            "",
            "## 当前下一步",
            "",
            f"**{focus['id']}：{focus['title']}**（{LABELS[focus['status']]}）。",
            "",
            focus["next_action"],
            "",
            "验收条件：",
            "",
            *[f"- {item}" for item in focus["acceptance"]],
        ]
    lines += ["", "## 已验证事实", ""]
    for evidence in data["evidence"]:
        lines += [
            f"- [{evidence['title']}]({evidence['url']})：{evidence['summary']} "
            f"范围：{evidence['scope']}。"
        ]
    blocked = [task for task in tasks.values() if task["status"] == "blocked"]
    lines += ["", "## 当前阻塞", ""]
    lines += (
        [f"- {task['id']}：{task['blocker']}" for task in blocked]
        if blocked
        else ["当前没有已确认的阻塞。集群操作前先确认 Cisco Secure Client 已连接学校 VPN。"]
    )
    lines += ["", "## 最近进展", ""]
    lines += [
        f"- {event['date']} · {event['title']}：{event['description']}"
        for event in recent_events(data)[:5]
    ]
    lines += [
        "",
        "## 结果边界",
        "",
        data["project"]["evidence_boundary"],
        "",
        "readiness 耗时与 APC 命中不作为调度优化收益；16K 是上下文上限，"
        "当前原生功能验证的输入约 2.2K tokens。",
        "",
    ]
    return "\n".join(lines)
